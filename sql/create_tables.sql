--creating tables
DROP TABLE IF EXISTS WORKLOAD_ACTIVITY CASCADE;
DROP TABLE IF EXISTS LEARNING_OUTCOME CASCADE;
DROP TABLE IF EXISTS PREREQUISITE CASCADE;
DROP TABLE IF EXISTS COMPULSORY_COURSE CASCADE;
DROP TABLE IF EXISTS ELECTIVE_COURSE CASCADE;
DROP TABLE IF EXISTS COURSE CASCADE;
DROP TABLE IF EXISTS SEMESTER CASCADE;
DROP TABLE IF EXISTS DEPARTMENT CASCADE;
DROP TABLE IF EXISTS UNIVERSITY CASCADE;

CREATE TABLE UNIVERSITY(
	Uni_id	 				INT					PRIMARY KEY,
	Uni_name				VARCHAR(100)		NOT NULL,
	Country					VARCHAR(100)							
);

CREATE TABLE DEPARTMENT(
	Dept_code				VARCHAR(20)			PRIMARY KEY,
	Dept_name				VARCHAR(100)		NOT NULL,
	Web_site				VARCHAR(100),
	Uni_id					INT REFERENCES UNIVERSITY(Uni_id)
					ON DELETE SET NULL		ON UPDATE CASCADE
);

CREATE TABLE SEMESTER(
	Sem_id					VARCHAR(20) 		PRIMARY KEY,
	Semester_no				INT,
	Year_level				INT,
	Term_string				VARCHAR(50)
);

CREATE TABLE COURSE(
	Course_code				VARCHAR(20)			PRIMARY KEY,
	Course_name				VARCHAR(100)		NOT NULL,
	Erasmus_eligibility		BOOLEAN				DEFAULT TRUE,
	Description				TEXT,
	Mode_of_del				VARCHAR(50),
	Language				VARCHAR(50),		
	Theory_hour				INT,
	Practice_hour			INT,
	ECTS					INT					NOT NULL,
	Is_active				BOOLEAN				DEFAULT TRUE,
    Lvl_unit				VARCHAR(100),
    Content					TEXT,
	Books					TEXT,
	Sem_id					VARCHAR(20) REFERENCES SEMESTER(Sem_id)
					ON DELETE SET NULL		ON UPDATE CASCADE,
	Dept_code 				VARCHAR(20) REFERENCES DEPARTMENT(Dept_code)
					ON DELETE SET NULL		ON UPDATE CASCADE			
);

CREATE TABLE PREREQUISITE(
	Course_code				VARCHAR(20) REFERENCES COURSE(Course_code),
	Prereq_code				VARCHAR(20) REFERENCES COURSE(Course_code),
	Prereq_type				VARCHAR(50),
	PRIMARY KEY(course_code,prereq_code)
);

CREATE TABLE COMPULSORY_COURSE(
	Course_code 			VARCHAR(20) REFERENCES COURSE(Course_code)
					ON DELETE CASCADE		ON UPDATE CASCADE,
	Is_department_core		BOOLEAN				DEFAULT TRUE,
	PRIMARY KEY(Course_code)
);

CREATE TABLE ELECTIVE_COURSE(
	Course_code 			VARCHAR(20) REFERENCES COURSE(Course_code)
					ON DELETE CASCADE		ON UPDATE CASCADE,
	Pool_name				VARCHAR(100),
	PRIMARY KEY(Course_code)
);

CREATE TABLE LEARNING_OUTCOME(
	Course_code				VARCHAR(20) REFERENCES COURSE(Course_code)
					ON DELETE CASCADE 		ON UPDATE CASCADE ,
	Outcome_order			INT				DEFAULT 0,
	Lo_count				INT,
	Learning_outcome		TEXT,
	PRIMARY KEY(Course_code, Outcome_order)
);

CREATE TABLE WORKLOAD_ACTIVITY(
	Course_code 			VARCHAR(20) REFERENCES COURSE(Course_code),
	Activity_name			VARCHAR(100)		NOT NULL,
	Quantity				INT,
	Duration_hour			INT,
	Percentage_contribution	INT,
	PRIMARY KEY(Course_code,Activity_name)
);
